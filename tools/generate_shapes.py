#!/usr/bin/env python3
"""Hitboxes from block models: for each listed block, the union of its model's elements (turned as its blockstate turns
it) becomes the block's shape, so the outline and collision match what is drawn. Writes util/ModelShapes.java.

Run from the repository root:  python3 tools/generate_shapes.py
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'main')
ASSETS = os.path.join(ROOT, 'resources', 'assets', 'arcane_artifacts')
OUT = os.path.join(ROOT, 'java', 'com', 'soulinchains', 'arcaneartifacts', 'util', 'ModelShapes.java')
BLOCKS = ['grave', 'empty_throne', 'research_table', 'alchemical_distiller', 'mana_pump', 'ritual_censer', 'catto_cushion']


def elements(ref, depth=0):
    ns, path = ref.split(':') if ':' in ref else ('minecraft', ref)
    if ns != 'arcane_artifacts' or depth > 6:
        return None
    p = os.path.join(ASSETS, 'models', path + '.json')
    if not os.path.exists(p):
        return None
    m = json.load(open(p))
    if 'elements' in m:
        return [(e['from'], e['to']) for e in m['elements']]
    return elements(m['parent'], depth + 1) if 'parent' in m else None


def turn_y(box, deg):
    (x1, y1, z1), (x2, y2, z2) = box
    for _ in range((deg // 90) % 4):
        # 90 degrees clockwise seen from above: north goes east
        x1, z1, x2, z2 = 16 - z2, x1, 16 - z1, x2
    return [x1, y1, z1], [x2, y2, z2]


def turn_x(box, deg):
    (x1, y1, z1), (x2, y2, z2) = box
    for _ in range((deg // 90) % 4):
        # 90 degrees about the x axis: north goes down... the outline only needs the extents
        y1, z1, y2, z2 = 16 - z2, y1, 16 - z1, y2
    return [x1, y1, z1], [x2, y2, z2]


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def fmt(v):
    v = round(v, 3)
    return ('%g' % v) + 'D'


lines = []
for block in BLOCKS:
    bs = json.load(open(os.path.join(ASSETS, 'blockstates', block + '.json')))
    for key, variant in bs['variants'].items():
        variant = variant[0] if isinstance(variant, list) else variant
        els = elements(variant['model'])
        if not els:
            continue
        boxes = []
        for box in els:
            box = turn_x(box, variant.get('x', 0))
            box = turn_y(box, variant.get('y', 0))
            (x1, y1, z1), (x2, y2, z2) = box
            x1, x2 = clamp(min(x1, x2), 0, 16), clamp(max(x1, x2), 0, 16)
            z1, z2 = clamp(min(z1, z2), 0, 16), clamp(max(z1, z2), 0, 16)
            y1, y2 = clamp(min(y1, y2), 0, 24), clamp(max(y1, y2), 0, 24)
            if x2 - x1 < 0.5 or y2 - y1 < 0.5 or z2 - z1 < 0.5:
                continue
            boxes.append('box(%s, %s, %s, %s, %s, %s)' % tuple(fmt(v) for v in (x1, y1, z1, x2, y2, z2)))
        if boxes:
            lines.append('        put("%s", "%s", %s);' % (block, key, ', '.join(boxes)))

java = '''package com.soulinchains.arcaneartifacts.util;

import com.soulinchains.arcaneartifacts.ArcaneArtifacts;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.Property;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;

/**
 * Hitboxes taken from the block models (generated by tools/generate_shapes.py - do not edit by hand): the union of a
 * model's elements, turned the way the blockstate turns the model, so a block's outline matches what is drawn.
 */
public final class ModelShapes {
    private record Entry(Map<String, String> when, VoxelShape shape) {
    }

    private static final Map<String, List<Entry>> TABLE = new HashMap<>();
    private static final Map<BlockState, VoxelShape> CACHE = new IdentityHashMap<>();

    static {
%s
    }

    private ModelShapes() {
    }

    private static VoxelShape box(double x1, double y1, double z1, double x2, double y2, double z2) {
        return Block.box(x1, y1, z1, x2, y2, z2);
    }

    private static void put(String block, String variant, VoxelShape... boxes) {
        Map<String, String> when = new HashMap<>();
        if (!variant.isEmpty()) {
            for (String pair : variant.split(",")) {
                String[] kv = pair.split("=");
                when.put(kv[0], kv[1]);
            }
        }
        TABLE.computeIfAbsent(block, k -> new ArrayList<>()).add(new Entry(when, Shapes.or(Shapes.empty(), boxes)));
    }

    /** The model's shape for this state, or {@code fallback} when the state's block is not in the table. */
    public static synchronized VoxelShape of(BlockState state, VoxelShape fallback) {
        VoxelShape cached = CACHE.get(state);
        if (cached != null) {
            return cached;
        }
        var key = BuiltInRegistries.BLOCK.getKey(state.getBlock());
        VoxelShape found = fallback;
        if (key.getNamespace().equals(ArcaneArtifacts.MODID)) {
            for (Entry entry : TABLE.getOrDefault(key.getPath(), List.of())) {
                if (matches(state, entry.when)) {
                    found = entry.shape;
                    break;
                }
            }
        }
        CACHE.put(state, found);
        return found;
    }

    private static boolean matches(BlockState state, Map<String, String> when) {
        for (Map.Entry<String, String> e : when.entrySet()) {
            Property<?> property = state.getBlock().getStateDefinition().getProperty(e.getKey());
            if (property == null || !name(state, property).equals(e.getValue())) {
                return false;
            }
        }
        return true;
    }

    private static <T extends Comparable<T>> String name(BlockState state, Property<T> property) {
        return property.getName(state.getValue(property));
    }
}
''' % '\n'.join(lines)
open(OUT, 'w').write(java)
print('wrote', os.path.relpath(OUT), len(lines), 'variants')
